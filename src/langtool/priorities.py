def core_priority(id):
    """Language.getPriorityForId of languagetool-core"""
    if id.upper() == 'TOO_LONG_SENTENCE':
        return -101
    if id == 'REPETITIONS_STYLE':
        return -55
    if 'STYLE' in id:
        return -50
    return 0


def priority_for_id(lang_code, id, extra=None):
    if extra and id in extra:
        return extra[id]
    if lang_code == 'de-DE-x-simple-language':
        if id == 'TOO_LONG_SENTENCE':
            return 10
        if id == 'LANGES_WORT':
            return -1
        lang_code = 'de'
    f = _BEFORE.get(lang_code)
    if f is not None:
        r = f(id)
        if r is not None:
            return r
    m = EXACT.get(lang_code)
    if m is not None and id in m:
        return m[id]
    f = _AFTER.get(lang_code)
    if f is not None:
        r = f(id)
        if r is not None:
            return r
    return core_priority(id)
